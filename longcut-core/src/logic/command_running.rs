use super::Context;
use crate::port::executor::{CommandPoll, ExecutorError, RunningCommand};
use crate::port::view::{CommandRunningViewModel, ViewAction, ViewModel};
use std::time::Duration;

/// How a watched command ended.
pub(crate) enum RunningResult {
    /// The command finished on its own, with its output or the details of its failure.
    Finished(Result<String, ExecutorError>),
    /// The user killed the command with a back key.
    Cancelled,
    /// The user killed the command with an exit key.
    Aborted,
    /// The user asked for the command to be killed, but it could not be ended and is in an
    /// unknown state; it may still be running.
    KillFailed(ExecutorError),
}

/// Watches a running command until it finishes or the user kills it.
///
/// The command is checked on between short waits for a key. Once it has outlived the delay, a
/// screen shows what runs and for how long, refreshed whenever the displayed second changes. A
/// back or exit key kills the command; any other key is dropped.
pub(crate) fn run_command_running_mode(
    ctx: &Context,
    title: &str,
    program: &str,
    mut running: Box<dyn RunningCommand>,
) -> RunningResult {
    /// How long a command runs unannounced before the running screen appears. A command that
    /// finishes within this time never shows a screen, so quick commands do not flash one.
    const RUNNING_SCREEN_DELAY: Duration = Duration::from_millis(200);

    /// How long each wait for a key lasts before the command is checked on again.
    const KEY_WAIT: Duration = Duration::from_millis(50);

    let started = ctx.clock.now();
    let mut shown_second = None;
    loop {
        running = match running.poll() {
            CommandPoll::Finished(result) => return RunningResult::Finished(result),
            CommandPoll::Running(running) => running,
        };

        let elapsed = ctx.clock.now().saturating_duration_since(started);
        if elapsed >= RUNNING_SCREEN_DELAY && shown_second != Some(elapsed.as_secs()) {
            render(ctx, title, program, elapsed);
            shown_second = Some(elapsed.as_secs());
        }

        if let Some(press) = ctx.keyboard.capture_within(KEY_WAIT) {
            if ctx.keys_back.contains(&press) {
                return kill(running, RunningResult::Cancelled);
            }
            if ctx.keys_exit.contains(&press) {
                return kill(running, RunningResult::Aborted);
            }
        }
    }
}

fn kill(running: Box<dyn RunningCommand>, outcome: RunningResult) -> RunningResult {
    match running.kill() {
        Ok(()) => outcome,
        Err(error) => RunningResult::KillFailed(error),
    }
}

fn render(ctx: &Context, title: &str, program: &str, elapsed: Duration) {
    let mut actions = vec![];
    for key in ctx.keys_back {
        actions.push((key, ViewAction::Kill));
    }
    for key in ctx.keys_exit {
        actions.push((key, ViewAction::Kill));
    }

    ctx.view
        .render(ViewModel::CommandRunning(CommandRunningViewModel {
            actions: &actions,
            command_name: title,
            program,
            elapsed,
        }));
}

#[cfg(test)]
mod tests {
    use crate::logic::Context;
    use crate::logic::command_execution::CommandExecutionResult::{Finished, KeepGoing};
    use crate::logic::command_execution::{CommandExecutionResult, run_command_execution_mode};
    use crate::model::command::{Command, CommandParameter};
    use crate::model::effect::{EffectTemplate, ShellCommandTemplate};
    use crate::model::key::{Key, Symbol};
    use crate::model::parameter::{ChooseParameter, ParameterDefinitionVariant};
    use crate::port::executor::ExecutorError;
    use crate::port::fakes::Event::{
        CommandFinishes, KeyPressed, KillsFail, StartsFail, StartsSucceed, TimePasses,
    };
    use crate::port::fakes::{Effect, Scenario, Screen};
    use std::time::Duration;

    fn back_key() -> Key {
        Key::new(Symbol::BACKSPACE)
    }

    fn exit_key() -> Key {
        Key::new(Symbol::ESCAPE)
    }

    fn retry_key() -> Key {
        Key::new(Symbol::RETURN)
    }

    /// A final command with one synchronous step and no parameters.
    fn sync_command(name: &str, program: &str) -> Command {
        let mut step = ShellCommandTemplate::new(program).unwrap();
        step.set_synchronous(true);
        let steps = vec![EffectTemplate::ShellCommand(step)];
        let mut command = Command::new(name.to_string(), steps, vec![]).unwrap();
        command.set_final(true);
        command
    }

    /// A command with one synchronous step that takes a parameter generated by a command.
    fn command_with_generated_parameter() -> Command {
        let devices =
            ChooseParameter::new(None, Some("bluetoothctl devices".to_string()), None).unwrap();
        let parameter = CommandParameter::new(
            "Device".to_string(),
            ParameterDefinitionVariant::Choose(devices),
        );
        let mut step = ShellCommandTemplate::new("bluetoothctl connect {0}").unwrap();
        step.set_synchronous(true);
        let steps = vec![EffectTemplate::ShellCommand(step)];
        Command::new("Connect".to_string(), steps, vec![parameter]).unwrap()
    }

    fn execute(ctx: &Context, command: &Command) -> CommandExecutionResult {
        run_command_execution_mode(ctx, command, &[])
    }

    fn started(program: &str) -> Effect {
        Effect::Started(program.to_string())
    }

    fn shows_running(command_name: &str, elapsed_secs: u64) -> Effect {
        Effect::Rendered(Screen::Running {
            command_name: command_name.to_string(),
            elapsed_secs,
        })
    }

    fn shows_error(error_type: &str) -> Effect {
        Effect::Rendered(Screen::Error {
            error_type: error_type.to_string(),
            retry_offered: true,
        })
    }

    fn shows_unrecoverable_error(error_type: &str) -> Effect {
        Effect::Rendered(Screen::Error {
            error_type: error_type.to_string(),
            retry_offered: false,
        })
    }

    #[test]
    fn command_finishing_before_the_delay_shows_no_screen() {
        let command = sync_command("Volume up", "wpctl set-volume");
        Scenario::new()
            .run(|ctx| execute(ctx, &command))
            .expect(started("wpctl set-volume"))
            .then(TimePasses(Duration::from_millis(50)))
            .then(CommandFinishes(Ok(String::new())))
            .returns(Finished);
    }

    #[test]
    fn command_outliving_the_delay_shows_the_running_screen_refreshed_each_second() {
        let command = sync_command("Connect", "bluetoothctl connect");
        Scenario::new()
            .run(|ctx| execute(ctx, &command))
            .expect(started("bluetoothctl connect"))
            .expect(shows_running("Connect", 0))
            .expect(shows_running("Connect", 1))
            .expect(shows_running("Connect", 2))
            .then(TimePasses(Duration::from_millis(2100)))
            .then(CommandFinishes(Ok(String::new())))
            .returns(Finished);
    }

    #[test]
    fn back_key_kills_the_command_and_keeps_going() {
        let command = sync_command("Connect", "bluetoothctl connect");
        Scenario::new()
            .run(|ctx| execute(ctx, &command))
            .expect(started("bluetoothctl connect"))
            .expect(shows_running("Connect", 0))
            .expect(shows_running("Connect", 1))
            .then(TimePasses(Duration::from_millis(1500)))
            .then(KeyPressed(back_key()))
            .expect(Effect::Killed)
            .returns(KeepGoing);
    }

    #[test]
    fn exit_key_kills_the_command_and_finishes() {
        let command = sync_command("Connect", "bluetoothctl connect");
        Scenario::new()
            .run(|ctx| execute(ctx, &command))
            .expect(started("bluetoothctl connect"))
            .expect(shows_running("Connect", 0))
            .then(TimePasses(Duration::from_millis(500)))
            .then(KeyPressed(exit_key()))
            .expect(Effect::Killed)
            .returns(Finished);
    }

    #[test]
    fn other_keys_are_dropped_while_the_command_runs() {
        let command = sync_command("Connect", "bluetoothctl connect");
        Scenario::new()
            .run(|ctx| execute(ctx, &command))
            .expect(started("bluetoothctl connect"))
            .expect(shows_running("Connect", 0))
            .then(TimePasses(Duration::from_millis(300)))
            .then(KeyPressed(Key::new(Symbol::from_char('x').unwrap())))
            .then(TimePasses(Duration::from_millis(300)))
            .then(KeyPressed(back_key()))
            .expect(Effect::Killed)
            .returns(KeepGoing);
    }

    #[test]
    fn failed_command_reaches_the_error_screen_with_retry_offered() {
        let command = sync_command("Connect", "bluetoothctl connect");
        let failure = ExecutorError::Runtime("no such device".to_string());
        Scenario::new()
            .run(|ctx| execute(ctx, &command))
            .expect(started("bluetoothctl connect"))
            .expect(shows_running("Connect", 0))
            .then(TimePasses(Duration::from_millis(300)))
            .then(CommandFinishes(Err(failure)))
            .expect(shows_error("Runtime error"))
            .then(TimePasses(Duration::from_millis(100)))
            .then(KeyPressed(exit_key()))
            .returns(Finished);
    }

    #[test]
    fn command_failing_to_start_reaches_the_error_screen() {
        let command = sync_command("Connect", "bluetoothctl connect");
        Scenario::new()
            .given(StartsFail)
            .run(|ctx| execute(ctx, &command))
            .expect(shows_error("Startup error"))
            .then(TimePasses(Duration::from_millis(100)))
            .then(KeyPressed(exit_key()))
            .returns(Finished);
    }

    #[test]
    fn retry_starts_the_command_again() {
        let command = sync_command("Connect", "bluetoothctl connect");
        Scenario::new()
            .given(StartsFail)
            .run(|ctx| execute(ctx, &command))
            .expect(shows_error("Startup error"))
            .then(TimePasses(Duration::from_millis(50)))
            .then(StartsSucceed)
            .then(TimePasses(Duration::from_millis(50)))
            .then(KeyPressed(retry_key()))
            .expect(started("bluetoothctl connect"))
            .then(TimePasses(Duration::from_millis(100)))
            .then(CommandFinishes(Ok(String::new())))
            .returns(Finished);
    }

    #[test]
    fn failed_kill_reaches_the_error_screen_without_retry() {
        let command = sync_command("Connect", "bluetoothctl connect");
        Scenario::new()
            .given(KillsFail)
            .run(|ctx| execute(ctx, &command))
            .expect(started("bluetoothctl connect"))
            .expect(shows_running("Connect", 0))
            .then(TimePasses(Duration::from_millis(500)))
            .then(KeyPressed(back_key()))
            .expect(shows_unrecoverable_error("Unknown error"))
            .then(TimePasses(Duration::from_millis(100)))
            .then(KeyPressed(back_key()))
            .returns(KeepGoing);
    }

    #[test]
    fn kill_during_option_generation_cancels_the_parameter_input() {
        let command = command_with_generated_parameter();
        Scenario::new()
            .run(|ctx| execute(ctx, &command))
            .expect(started("bluetoothctl devices"))
            .expect(shows_running("Device", 0))
            .then(TimePasses(Duration::from_millis(500)))
            .then(KeyPressed(back_key()))
            .expect(Effect::Killed)
            .returns(KeepGoing);
    }

    #[test]
    fn failed_kill_during_option_generation_reaches_the_error_screen_without_retry() {
        let command = command_with_generated_parameter();
        Scenario::new()
            .given(KillsFail)
            .run(|ctx| execute(ctx, &command))
            .expect(started("bluetoothctl devices"))
            .expect(shows_running("Device", 0))
            .then(TimePasses(Duration::from_millis(500)))
            .then(KeyPressed(back_key()))
            .expect(shows_unrecoverable_error("Unknown error"))
            .then(TimePasses(Duration::from_millis(100)))
            .then(KeyPressed(exit_key()))
            .returns(Finished);
    }
}
